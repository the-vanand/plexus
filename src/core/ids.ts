/**
 * Короткие устойчивые id узлов. Эти же id становятся якорями data-plx-id
 * в сгенерированном коде и маркерами PLX-SLOT, по которым при повторной
 * генерации сохраняется дописанный пользователем код.
 *
 * ПОЧЕМУ ЗДЕСЬ ЕСТЬ ДЕТЕРМИНИРОВАННЫЙ РЕЖИМ.
 *
 * Внутри одного документа id стабильны, поэтому регенерация кода из
 * сохранённого проекта воспроизводима. Но при КАЖДОМ импорте того же самого
 * сайта узлы создаются заново, и `Math.random()` даёт другие id. Следствия
 * измеримы:
 *
 *  - вывод кодогена меняется от прогона к прогону (id уезжают в разметку, а
 *    их хвост — ещё и в имена CSS-классов при коллизии), поэтому сравнить
 *    два прогона побайтово нельзя, и CI не может гейтить размер вывода;
 *  - сохранённый проект нельзя осмысленно держать в git: повторный импорт
 *    того же сайта даёт полностью другой файл при том же содержании;
 *  - регрессию в импорте не отличить от смены случайных id.
 *
 * Решение НЕ в том, чтобы сделать id позиционными в кодогене: маркеры
 * PLX-SLOT привязаны к id, и при вставке узла позиционный ключ сдвинулся бы,
 * а дописанный пользователем код потерялся. Поэтому детерминированность
 * вводится там, где возникает случайность, — в момент создания узлов при
 * импорте. Интерактивное создание узлов в редакторе остаётся случайным:
 * там воспроизводимость не нужна, а уникальность важнее.
 */

/** Активный детерминированный режим. null — обычная случайная генерация. */
let det: { seed: number; counter: number; used: Set<string> } | null = null;

/** FNV-1a: короткий стабильный хеш строки. Нужен только как затравка. */
function hashString(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i += 1) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/** Перемешивание затравки со счётчиком → 6 знаков base36. */
function mix(seed: number, counter: number): string {
  let x = (seed ^ Math.imul(counter, 0x9e3779b1)) >>> 0;
  x ^= x >>> 16;
  x = Math.imul(x, 0x7feb352d) >>> 0;
  x ^= x >>> 15;
  x = Math.imul(x, 0x846ca68b) >>> 0;
  x ^= x >>> 16;
  return (x >>> 0).toString(36).padStart(6, "0").slice(-6);
}

export function uid(prefix = "n"): string {
  if (det) {
    /* Уникальность гарантируется явной проверкой, а не размером
       пространства: 6 знаков base36 — это около двух миллиардов значений,
       коллизия на 250 узлах маловероятна, но «маловероятна» и «невозможна» —
       разные вещи, а совпадение id разрушило бы документ. */
    for (;;) {
      det.counter += 1;
      const id = `${prefix}_${mix(det.seed, det.counter)}`;
      if (!det.used.has(id)) {
        det.used.add(id);
        return id;
      }
    }
  }
  const rand = Math.random().toString(36).slice(2, 8);
  return `${prefix}_${rand}`;
}

/**
 * Выполнить `fn` так, чтобы все созданные внутри id зависели только от
 * `seed` и порядка создания.
 *
 * Затравку задаёт вызывающий, и в неё обязано входить состояние документа
 * (например, число уже существующих узлов). Иначе два импорта одного сайта
 * в один документ дали бы одинаковые id и сломали его.
 *
 * Режим восстанавливается в finally и корректно вкладывается: вложенный
 * вызов не сбрасывает счётчик внешнего.
 */
export function withDeterministicIds<T>(seed: string, fn: () => T): T {
  const prev = det;
  det = { seed: hashString(seed), counter: 0, used: new Set() };
  try {
    return fn();
  } finally {
    det = prev;
  }
}

/** Идут ли сейчас детерминированные id. Нужно стендам и диагностике. */
export function isDeterministicIds(): boolean {
  return det !== null;
}
